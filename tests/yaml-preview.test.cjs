const assert = require('node:assert/strict');
global.window = {};
require('../editor-assets/yaml-preview.js');

const formatYaml = window.ZMenuEditorFormatYaml;
const credit = '# Generated by zMenu Menu Editor';
const defaults = {comments:true, spacing:true, docLinks:true, detail:'full'};
const raw = [
  '# Documentation: https://docs.example.test/menu',
  '# Menu comment',
  'name: Example',
  '',
  'items:',
  '  website:',
  '    open-link: https://example.test/menu',
  "    texture: 'https://textures.minecraft.net/texture/example'",
  '    lore:',
  "      - '<click:open_url:https://example.test>Open</click>'",
  '',
  ''
].join('\r\n');

const full = formatYaml(raw, defaults);
assert.ok(full.startsWith(credit + '\n'));
assert.ok(full.includes('# Documentation: https://docs.example.test/menu\n'));
assert.ok(full.includes('# Menu comment\n'));
assert.ok(full.includes('name: Example\n\nitems:'));
assert.ok(!full.includes('\r'));
assert.ok(full.endsWith('\n'));
assert.ok(!full.endsWith('\n\n'));
assert.equal(formatYaml(full, defaults), full);

const withoutDocLinks = formatYaml(raw, {...defaults, docLinks:false});
assert.ok(!withoutDocLinks.includes('# Documentation:'));
assert.ok(withoutDocLinks.includes('# Menu comment\n'));
assert.ok(withoutDocLinks.includes('    open-link: https://example.test/menu\n'));
assert.ok(withoutDocLinks.includes("    texture: 'https://textures.minecraft.net/texture/example'\n"));
assert.ok(withoutDocLinks.includes("      - '<click:open_url:https://example.test>Open</click>'\n"));
assert.ok(withoutDocLinks.startsWith(credit + '\n'));

const withoutComments = formatYaml(raw, {...defaults, comments:false});
assert.ok(!withoutComments.includes('# Documentation:'));
assert.ok(!withoutComments.includes('# Menu comment'));
assert.ok(withoutComments.startsWith(credit + '\n'));
assert.ok(withoutComments.includes('name: Example\n\nitems:'));
assert.ok(withoutComments.includes('open-link: https://example.test/menu'));

const compact = formatYaml(raw, {...defaults, comments:false, spacing:false, docLinks:false});
assert.ok(!compact.includes('\n\n'));
assert.ok(compact.startsWith(credit + '\n'));
assert.ok(compact.includes('open-link: https://example.test/menu'));
assert.equal(compact.split('\n').filter(line => line === credit).length, 1);
assert.equal(formatYaml(compact, defaults), compact);
assert.equal(formatYaml('', defaults), credit + '\n');
assert.equal(formatYaml('name: Example\rsize: 9\r', defaults), credit + '\nname: Example\nsize: 9\n');
console.log('PASS: YAML preview options preserve business URLs, credit, and normalized newlines');
